
# Latihan 3: Manipulasi List

nilai = [75, 80, 65]

# Mengubah nilai indeks 1
nilai[1] = 82

# Menambahkan nilai di akhir list
nilai.append(90)

# Menyisipkan nilai 70 pada indeks 1
nilai.insert(1, 70)

# Menghapus nilai 65
nilai.remove(65)

# Menampilkan hasil akhir
print("List setelah dimanipulasi =", nilai)
