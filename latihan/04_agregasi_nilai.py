
# Latihan 4: Agregasi Nilai

# Data nilai mahasiswa
nilai = [75, 80, 65, 90, 88]

# Menghitung statistik nilai
total = sum(nilai)
rata_rata = sum(nilai) / len(nilai)
minimum = min(nilai)
maksimum = max(nilai)

# Menampilkan hasil
print(f"Total = {total}")
print(f"Rata-rata = {rata_rata:.2f}")
print(f"Minimum = {minimum}")
print(f"Maksimum = {maksimum}")
