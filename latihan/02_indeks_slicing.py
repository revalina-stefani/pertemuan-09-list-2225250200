
# Latihan 2: Indeks dan Slicing

# Menyimpan enam nilai mahasiswa
nilai = [75, 80, 65, 90, 88, 70]

# Menampilkan elemen berdasarkan indeks
print("Nilai pertama =", nilai[0])
print("Nilai terakhir =", nilai[-1])

# Mengambil sebagian elemen list
print("Tiga nilai awal =", nilai[:3])
print("Indeks 1 sampai 3 =", nilai[1:4])
